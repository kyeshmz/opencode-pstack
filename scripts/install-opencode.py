#!/usr/bin/env python3
"""Build a native OpenCode installation without modifying upstream source files."""

import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone


COMMAND_MARKER = '<!-- generated by pstack install.sh (do not edit: overwritten on reinstall) -->'
START = '<!-- pstack:opencode:start -->'
END = '<!-- pstack:opencode:end -->'


def normalize_skills(skills):
    for md in skills.rglob('SKILL.md'):
        text = md.read_text()
        match = re.match(r'\A---\n(.*?)\n---', text, re.S)
        if not match:
            raise ValueError(f'{md}: missing skill frontmatter')
        fm = re.sub(r'^name:.*$', f'name: {md.parent.name}', match[1], count=1, flags=re.M)
        # disable-model-invocation is supported natively by OpenCode V2.
        # Do not inject speculative opencode/slash metadata.
        md.write_text(text[:match.start(1)] + fm + text[match.end(1):])


def description(text):
    """Read upstream's scalar and folded/block descriptions without a YAML dependency."""
    fm = re.match(r'\A---\n(.*?)\n---', text, re.S)[1]
    match = re.search(r'^description:[ \t]*(.*)$', fm, re.M)
    if not match:
        raise ValueError('missing skill description')
    value = match[1].strip()
    if value in ('>', '>-', '>+', '|', '|-', '|+'):
        lines = []
        for line in fm[match.end():].splitlines():
            if not line.strip():
                continue
            if not line.startswith((' ', '\t')):
                break
            lines.append(line.strip())
        value = ' '.join(lines)
    elif value.startswith('"') and value.endswith('"'):
        import json
        value = json.loads(value)
    elif value.startswith("'") and value.endswith("'"):
        value = value[1:-1].replace("''", "'")
    if not value:
        raise ValueError('empty skill description')
    return value


def commands(skills, dest):
    import json
    dest.mkdir(parents=True, exist_ok=True)
    slugs = set()
    for md in sorted(skills.rglob('SKILL.md')):
        slug = md.parent.name
        if slug in slugs:
            raise ValueError(f'duplicate skill ID: {slug}')
        slugs.add(slug)
        path = dest / f'{slug}.md'
        if path.exists() and COMMAND_MARKER not in path.read_text():
            print(f'keeping custom command: {path}')
            continue
        path.write_text(
            f'---\ndescription: {json.dumps(description(md.read_text()))}\n---\n'
            f'{COMMAND_MARKER}\n\n'
            f'Use the `skill` tool with `id: "{slug}"` to load the full skill, '
            'then follow it for this task. Resolve bundled resources from its '
            'reported base directory and generated outputs from the target project.\n\n'
            '$ARGUMENTS\n'
        )
    for path in dest.glob('*.md'):
        if path.stem not in slugs and COMMAND_MARKER in path.read_text():
            path.unlink()


def instructions(config, dry_run=False):
    models = config / 'instructions/pstack-models.md'
    agents = config / 'AGENTS.md'
    block = (
        f'{START}\n## pstack for OpenCode\n\n'
        f'When using pstack workflows, read `{models}` for per-role model choices. '
        'Use only models confirmed available by the host and allowed by its instructions; '
        '`auto` and `inherit-parent` mean omit the subagent model argument. '
        'Do not apply pstack delegation or model choices to unrelated tasks.\n\n'
        'Resolve bundled resources from the loaded skill base directory. '
        'Write generated project skills to `<target-repository>/.opencode/skills/<skill-id>/SKILL.md`. '
        f'Write global skills to `{config}/skills/<skill-id>/SKILL.md` only when requested. '
        'Never write generated project files into the installed pstack pack.\n'
        f'{END}'
    )
    text = agents.read_text() if agents.exists() else ''
    if START in text or END in text:
        if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
            raise ValueError(f'{agents}: malformed pstack managed block; refusing to overwrite')
        text = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text += ('\n\n' if text and not text.endswith('\n\n') else '') + block + '\n'
    if not dry_run and (not agents.exists() or agents.read_text() != text):
        if agents.exists():
            shutil.copy2(agents, str(agents) + '.bak-pstack')
        agents.write_text(text)
    return text


def snapshot_changes(stage, config, agents_text):
    """Back up only existing files this install will overwrite or remove."""
    paths = set()
    for tree in ('skills', 'agents', 'commands', 'pstack'):
        for source in (stage / tree).rglob('*'):
            if not source.is_file():
                continue
            relative = source.relative_to(stage)
            target = config / relative
            if not target.is_file():
                continue
            if tree == 'commands' and COMMAND_MARKER not in target.read_text():
                continue
            if source.read_bytes() != target.read_bytes():
                paths.add(relative)
    for target in (config / 'commands').glob('*.md'):
        if not (stage / 'commands' / target.name).exists() and COMMAND_MARKER in target.read_text():
            paths.add(target.relative_to(config))
    agents = config / 'AGENTS.md'
    if agents.is_file() and agents.read_text() != agents_text:
        paths.add(Path('AGENTS.md'))
    if not paths:
        return
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S.%fZ')
    backup = config.parent / 'opencode-pstack-backups' / config.name / stamp
    backup.mkdir(parents=True, mode=0o700)
    for relative in sorted(paths):
        destination = backup / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(config / relative, destination)
    print(f'backed up {len(paths)} existing pstack files -> {backup}')


def prepare_guides(root, stage, config):
    pack = stage / 'pstack'
    shutil.copytree(root / 'docs', pack / 'docs')
    shutil.copy2(root / 'INSTALL.md', pack / 'README.md')
    for md in (pack / 'docs').rglob('*.md'):
        text = md.read_text()
        text = text.replace('../../skills/', '../../../skills/')
        text = text.replace('~/.cursor/rules/pstack-models.mdc', str(config / 'instructions/pstack-models.md'))
        text = text.replace('~/.cursor/skills/', str(config / 'skills') + '/')
        text = text.replace('.cursor/skills/', '.opencode/skills/')
        overlay = root / 'opencode/docs' / md.relative_to(pack / 'docs')
        if overlay.is_file():
            text = overlay.read_text().replace('{{CONFIG_DIR}}', str(config))
        md.write_text(
            '> OpenCode port: use the installed skills and [installation guide](../../README.md) '
            'for host-specific behavior. Cursor Custom Modes, cloud agents, plugins, '
            'and automation services described in this upstream guide are not OpenCode features.\n\n' + text
        )


def main(root, config):
    root, config = root.resolve(), config.expanduser().resolve()
    # Validate/convert in staging: an upstream wording change must not leave
    # partially converted global skills behind.
    with tempfile.TemporaryDirectory(prefix='pstack-opencode-') as temporary:
        stage = Path(temporary)
        for tree in ('skills', 'agents'):
            shutil.copytree(root / tree, stage / tree, ignore=shutil.ignore_patterns('opencode-port-agent.md'))
        environment = dict(os.environ, PSTACK_OPENCODE_CONFIG_DIR=str(config))
        subprocess.run([
            sys.executable, str(root / 'scripts/opencode-transform.py'),
            str(root / 'skills'), str(stage / 'skills'),
            str(root / 'agents'), str(stage / 'agents'),
        ], check=True, env=environment)
        normalize_skills(stage / 'skills')
        # Generate/validate every command before touching the live install.
        commands(stage / 'skills', stage / 'commands')
        prepare_guides(root, stage, config)
        agents_text = instructions(config, dry_run=True)
        snapshot_changes(stage, config, agents_text)
        config.mkdir(parents=True, exist_ok=True)
        for tree in ('skills', 'agents', 'pstack'):
            shutil.copytree(stage / tree, config / tree, dirs_exist_ok=True)
        commands(stage / 'skills', config / 'commands')

    # Preserve user-selected role choices on reinstall.
    models = config / 'instructions/pstack-models.md'
    models.parent.mkdir(parents=True, exist_ok=True)
    if not models.exists():
        shutil.copy2(root / 'opencode/pstack-models.md', models)
    instructions(config)

    print(f'installed OpenCode skills, agents, commands, guides and instructions -> {config}')


if __name__ == '__main__':
    main(Path(sys.argv[1]), Path(sys.argv[2]))
